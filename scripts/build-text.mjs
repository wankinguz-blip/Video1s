// Bakes the particle targets for the word "VANKING" into src/assets/vanking-text.js.
// Points are normalised: x, y in units of cap height, centred on the word. Each point also
// records its letter index (0..6) and whether it lies on the glyph edge.
//   node scripts/build-text.mjs
import { createCanvas, GlobalFonts } from '@napi-rs/canvas';
import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';

// small deterministic random generator (same sequence as the first version of the show)
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const WORD = 'VANKING';
const fontFile = execSync("fc-match -f '%{file}' 'DejaVu Sans:bold'").toString().trim();
GlobalFonts.registerFromPath(fontFile, 'VKBold');

const SIZE = 600, TRACK = 0.07; // tracking in em
const c = createCanvas(4600, 900);
const ctx = c.getContext('2d');
ctx.font = `${SIZE}px VKBold`;
ctx.textBaseline = 'alphabetic';
ctx.fillStyle = '#fff';
// lay out letters manually with consistent tracking
let x = 60;
const letters = [];
for (const ch of WORD) {
  const w = ctx.measureText(ch).width;
  letters.push({ ch, x0: x, x1: x + w });
  ctx.fillText(ch, x, 720);
  x += w + TRACK * SIZE;
}
const img = ctx.getImageData(0, 0, c.width, c.height).data;
const A = (px, py) => (px < 0 || py < 0 || px >= c.width || py >= c.height ? 0 : img[(py * c.width + px) * 4 + 3]);
// bounds
let bx0 = 1e9, by0 = 1e9, bx1 = -1, by1 = -1;
for (let py = 0; py < c.height; py++) for (let px = 0; px < c.width; px++) if (A(px, py) > 127) {
  if (px < bx0) bx0 = px; if (px > bx1) bx1 = px; if (py < by0) by0 = py; if (py > by1) by1 = py;
}
const capH = by1 - by0, cx = (bx0 + bx1) / 2, cy = (by0 + by1) / 2;
const rnd = mulberry32(2024);
const pts = [];
const letterOf = (px) => { let best = 0, bd = 1e9; letters.forEach((l, i) => { const d = px < l.x0 ? l.x0 - px : px > l.x1 ? px - l.x1 : 0; if (d < bd) { bd = d; best = i; } }); return best; };
// 1) interior: jittered hex grid
const d = capH * 0.04;
for (let row = 0, py = by0; py <= by1; row++, py += d * 0.866) {
  for (let px = bx0 + (row % 2 ? d / 2 : 0); px <= bx1; px += d) {
    const jx = px + (rnd() - 0.5) * d * 0.35, jy = py + (rnd() - 0.5) * d * 0.35;
    if (A(Math.round(jx), Math.round(jy)) > 140) pts.push([jx, jy, 0]);
  }
}
// 2) edges: boundary pixels thinned by minimum spacing
const edgeSpacing = capH * 0.026;
const edge = [];
for (let py = by0 - 1; py <= by1 + 1; py += 2) for (let px = bx0 - 1; px <= bx1 + 1; px += 2) {
  const a = A(px, py) > 127;
  if (a && (A(px + 2, py) <= 127 || A(px - 2, py) <= 127 || A(px, py + 2) <= 127 || A(px, py - 2) <= 127)) edge.push([px, py]);
}
const cell = new Map();
const key = (px, py) => `${Math.floor(px / edgeSpacing)},${Math.floor(py / edgeSpacing)}`;
for (const [px, py] of edge) {
  let ok = true;
  const gx = Math.floor(px / edgeSpacing), gy = Math.floor(py / edgeSpacing);
  for (let ix = -1; ix <= 1 && ok; ix++) for (let iy = -1; iy <= 1 && ok; iy++) {
    for (const q of cell.get(`${gx + ix},${gy + iy}`) || []) if (Math.hypot(q[0] - px, q[1] - py) < edgeSpacing) { ok = false; break; }
  }
  if (!ok) continue;
  const k = key(px, py);
  if (!cell.has(k)) cell.set(k, []);
  cell.get(k).push([px, py]);
  pts.push([px, py, 1]);
}
const out = pts.map(([px, py, e]) => [+((px - cx) / capH).toFixed(4), +((py - cy) / capH).toFixed(4), letterOf(px), e]);
const width = (bx1 - bx0) / capH;
writeFileSync(new URL('../src/assets/vanking-text.js', import.meta.url),
  `// AUTO-GENERATED by scripts/build-text.mjs (font: DejaVu Sans Bold, tracking ${TRACK} em) — do not edit.\n` +
  `// [x, y, letterIndex, isEdge] in units of cap height, centred on the word "${WORD}".\n` +
  `export const TEXT_WIDTH = ${width.toFixed(4)};\nexport const TEXT_POINTS = ${JSON.stringify(out)};\n`);
console.log(`points: ${out.length} (edge ${out.filter((p) => p[3]).length}), width/capH = ${width.toFixed(3)}`);
// preview
const pv = createCanvas(1400, 260), pc = pv.getContext('2d');
pc.fillStyle = '#0b1442'; pc.fillRect(0, 0, 1400, 260);
pc.fillStyle = '#fff';
for (const [px, py] of out) { pc.beginPath(); pc.arc(700 + px * 180, 130 + py * 180, 1.6, 0, 7); pc.fill(); }
mkdirSync(new URL('../out/', import.meta.url), { recursive: true });
writeFileSync(new URL('../out/text-preview.png', import.meta.url), pv.toBuffer('image/png'));
